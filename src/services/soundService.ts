  // Final Fantasy Victory Fanfare motif
  public playVictory() {
    this.playVictoryFanfare();
  }

  public playVictoryFanfare() {
    if (!this.enabled) return;
    this.initCtx();
    if (!this.ctx) return;

    try {
      const now = this.ctx.currentTime;
      // Iconic triplet-style victory fanfare rhythm
      const fanfareNotes = [
        { freq: 523.25, time: 0.0, dur: 0.12 }, // C
        { freq: 523.25, time: 0.13, dur: 0.12 }, // C
        { freq: 523.25, time: 0.26, dur: 0.12 }, // C
        { freq: 523.25, time: 0.42, dur: 0.32 }, // C long
        { freq: 415.30, time: 0.80, dur: 0.32 }, // G#
        { freq: 466.16, time: 1.15, dur: 0.32 }, // A#
        { freq: 523.25, time: 1.50, dur: 0.22 }, // C
        { freq: 466.16, time: 1.74, dur: 0.14 }, // A#
        { freq: 523.25, time: 1.90, dur: 0.65 }  // C finale
      ];

      fanfareNotes.forEach((n) => {
        const osc = this.ctx!.createOscillator();
        const gain = this.ctx!.createGain();

        osc.type = 'triangle';
        osc.frequency.setValueAtTime(n.freq, now + n.time);

        gain.gain.setValueAtTime(this.volume * 0.35, now + n.time);
        gain.gain.exponentialRampToValueAtTime(0.001, now + n.time + n.dur);

        osc.connect(gain);
        gain.connect(this.ctx!.destination);

        osc.start(now + n.time);
        osc.stop(now + n.time + n.dur);
      });
    } catch {
      // Ignore
    }
  }

